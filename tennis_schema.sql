create table ATPMatches
    (tourney_id         integer,
     match_num          integer,
     wid                integer,
     wseed              integer,
     wname              text,
     wrank              integer,
     wrank_points       integer,
     lid                integer,
     lseed              integer,
     lname              text,
     lrank              integer,
     lrank_points       integer,
     score              text,
     best_of            integer,
     round              text,
     minutes            integer,
     w_ace              integer,
     w_df               integer,
     w_svpt             integer,
     w_1stIn            integer,
     w_1stWon           integer,
     w_2ndWon           integer,
     w_SvGms            integer,
     w_bpSaved          integer,
     w_bpFaced          integer,
     l_ace              integer,
     l_df               integer,
     l_svpt             integer,
     l_1stIn            integer,
     l_1stWon           integer,
     l_2ndWon           integer,
     l_SvGms            integer,
     l_bpSaved          integer,
     l_bpFaced          integer,
     primary key(tourney_id, match_num),
     foreign key (wid) references Players(pid),
     foreign key (lid) references Players(pid),
     foreign key (tourney_id) references Tournaments(tid)
);

