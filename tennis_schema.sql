create table Tournaments
    (tid            integer,
     name           text,
     surface        text,
     draw_size      text,
     tourney_level  text,
     indoor         boolean,
     date           date,
     primary key (tid)
);

create table Players
    (pid            text,
     name           text,
     birthdate      text,
     height         integer,
     turned_pro      integer,
     birthplace     text,
     coaches        text,
     dominant_hand   text,
     backhand       text,
     nationality    text,
     primary key(pid)
);

create table Rankings
    (pid            text,
     rank           integer,
     points         integer,
     date           date,
     primary key(pid, date)
    )
